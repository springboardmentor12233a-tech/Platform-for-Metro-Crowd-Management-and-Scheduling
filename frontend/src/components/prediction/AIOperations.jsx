import {

Shield,

AlertTriangle,

Train,

Users,

CheckCircle,

} from "lucide-react";

export default function AIOperations({

prediction

}){

const actions=[];

if(prediction>=20){

actions.push({

icon:Train,

title:"Increase Train Frequency",

status:"Critical"

});

actions.push({

icon:Users,

title:"Deploy Platform Staff",

status:"Recommended"

});

}

else if(prediction>=10){

actions.push({

icon:AlertTriangle,

title:"Monitor Passenger Flow",

status:"Watch"

});

}

else{

actions.push({

icon:CheckCircle,

title:"Current Schedule is Optimal",

status:"Healthy"

});

}

return(

<div className="rounded-3xl bg-white border shadow-xl">

<div className="border-b p-6 flex items-center gap-3">

<Shield className="text-indigo-600"/>

<h2 className="text-2xl font-bold">

AI Operational Actions

</h2>

</div>

<div className="space-y-4 p-6">

{actions.map((item,index)=>(

<div

key={index}

className="rounded-2xl border bg-slate-50 p-5 flex justify-between items-center"

>

<div className="flex items-center gap-4">

<item.icon className="text-indigo-600"/>

<div>

<h3 className="font-semibold">

{item.title}

</h3>

<p className="text-sm text-slate-500">

Generated by AI

</p>

</div>

</div>

<span className="rounded-full bg-indigo-100 px-4 py-2 text-indigo-700 text-sm">

{item.status}

</span>

</div>

))}

</div>

</div>

)

}